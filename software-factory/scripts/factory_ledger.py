#!/usr/bin/env python3
"""Append-only merge ledger for the software factory.

Source of truth: $FACTORY_LEDGER_DIR/merges.jsonl (one JSON row per line).
Readable view:   $FACTORY_LEDGER_DIR/MERGES.md (regenerated from the JSONL).

Usage:
  factory_ledger.py append     # JSON row on stdin
  factory_ledger.py render     # rebuild MERGES.md
  factory_ledger.py tail [N]   # print the last N rows
  factory_ledger.py rows

Do not hand-edit either file. A later row for the same repo and PR carries
the new state. Times use FACTORY_TZ (default UTC).
"""
from __future__ import annotations

import datetime as dt
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import factory_paths  # noqa: E402

FIELDS = [
    "time", "event", "repo", "pr", "pr_url", "title", "head_sha", "merge_sha",
    "merged_by", "blast_tier", "checks", "portback", "revert", "note",
]


def _paths():
    d = factory_paths.ledger_dir()
    return d, os.path.join(d, "merges.jsonl"), os.path.join(d, "MERGES.md")


def now_stamp():
    t = dt.datetime.now(factory_paths.tz()).replace(microsecond=0)
    return t.isoformat()


def append(row: dict, render_md: bool = True) -> dict:
    """Append one row. Never edits or deletes earlier rows."""
    ledger, jsonl, _md = _paths()
    os.makedirs(ledger, exist_ok=True)
    rec = {k: row.get(k, "") for k in FIELDS}
    rec.update({k: v for k, v in row.items() if k not in rec})
    if rec.get("time_local") and not rec.get("time"):
        rec["time"] = rec["time_local"]
    if not rec["time"]:
        rec["time"] = now_stamp()
    if rec.get("pr") and not rec.get("pr_url") and rec.get("repo"):
        rec["pr_url"] = f"https://github.com/{rec['repo']}/pull/{rec['pr']}"
    with open(jsonl, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, sort_keys=False) + "\n")
    if render_md:
        render()
    return rec


def rows():
    _ledger, jsonl, _md = _paths()
    if not os.path.exists(jsonl):
        return []
    out = []
    with open(jsonl, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def row_time(row: dict) -> str:
    return str(row.get("time") or row.get("time_local") or "")


def _cell(v):
    if isinstance(v, (list, dict)):
        v = json.dumps(v)
    return str(v if v is not None else "").replace("|", "/").replace("\n", " ")


def _short(sha):
    return (sha or "")[:8]


def render():
    _ledger, _jsonl, md = _paths()
    rs = rows()
    by_day = {}
    for r in rs:
        by_day.setdefault(row_time(r)[:10], []).append(r)
    zone = factory_paths.timezone_name()
    lines = [
        "# Factory merge ledger",
        "",
        "Generated from merges.jsonl by scripts/factory_ledger.py. Do not edit this file.",
        f"Times are in {zone}.",
        "Each row is one event. A later row for the same PR carries the newer state.",
        "",
        f"Rows: {len(rs)}. Auto-merges: "
        f"{sum(1 for r in rs if r.get('event') == 'merged' and r.get('merged_by') == 'auto')}. "
        f"Reverts: {sum(1 for r in rs if r.get('event') in ('reverted', 'revert_opened'))}.",
        "",
    ]
    for day in sorted(by_day, reverse=True):
        lines += [
            f"## {day}",
            "",
            "| Time | Event | PR | Title | Head | Merge | By | Blast | Checks | Port-back | Revert |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in sorted(by_day[day], key=lambda x: row_time(x)):
            stamp = row_time(r)
            pr = (
                f"[{r['repo'].split('/')[-1]}#{r['pr']}]({r.get('pr_url', '')})"
                if r.get("pr") else _cell(r.get("repo"))
            )
            lines.append("| " + " | ".join([
                stamp[11:16] if len(stamp) >= 16 else stamp,
                _cell(r.get("event")),
                pr,
                _cell(r.get("title"))[:70],
                _short(r.get("head_sha")),
                _short(r.get("merge_sha")),
                _cell(r.get("merged_by")),
                _cell(r.get("blast_tier")),
                _cell(r.get("checks"))[:60],
                _cell(r.get("portback"))[:90],
                _cell(r.get("revert")),
            ]) + " |")
        lines.append("")
    os.makedirs(os.path.dirname(md) or ".", exist_ok=True)
    tmp = md + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, md)
    return md


def main():
    a = sys.argv[1:]
    cmd = a[0] if a else ""
    if cmd in ("", "-h", "--help"):
        print(__doc__)
        return
    if cmd == "append":
        raw = sys.stdin.read().strip()
        if not raw:
            print("factory_ledger append needs a JSON row on stdin", file=sys.stderr)
            sys.exit(2)
        print(json.dumps(append(json.loads(raw))))
        return
    if cmd == "render":
        print(render())
        return
    if cmd == "rows":
        for r in rows():
            print(json.dumps(r))
        return
    if cmd == "tail":
        n = int(a[1]) if len(a) > 1 else 10
        for r in rows()[-n:]:
            print(json.dumps(r))
        return
    print(__doc__)
    sys.exit(1)


if __name__ == "__main__":
    main()
